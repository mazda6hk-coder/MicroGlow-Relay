"""版式度量：垂直节奏、间距与组件尺寸的唯一来源。

任务书 v0.9 第 2 节只钉死了字号与圆角，间距明确留给实现决定。这里把它定成
一套**有名字、有用途**的刻度，视图只引用名字，不再出现裸数字。

三条纪律：

1. **间距走一套刻度**。纵向只用 8 的倍数（4 用于同一行内的微调），保证
   每一屏的节奏是同一个拍子。想加 21px 这种数，先问它属于哪一档。
2. **尺寸表达角色，不表达坐标**。``RING`` 是"微光圆环该多大"，
   不是"参考图上量到多大"。参考图是效果图，不是从本代码渲染出来的，
   它的像素坐标不能当规格用。
3. **容器尺寸优先由内容决定**。只有需要"视觉重量"的地方（总里程面板）
   才给下限，且给出理由。

改版时只改这个文件。
"""
